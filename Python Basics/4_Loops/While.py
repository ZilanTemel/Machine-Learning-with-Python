# Initialize the variable 'i' with a starting value
i = 1  # We start at 1 because we want to count from 1 upwards

# The while loop will continue executing the code inside it
# as long as the condition 'i <= 5' is True.
while i <= 5:
    # Inside the loop, the current value of 'i' is printed
    print(i)  # Prints the value of 'i' during each loop iteration

    # After printing, 'i' is incremented by 1
    i += 1  # i = i + 1, which increases the value of 'i' by 1 after each iteration

# After the loop ends, the program prints a message saying the loop is over
print("Loop has ended.")  # This will print once 'i' exceeds 5 and the loop condition is no longer true
